"""
Bitwise Operators - Understand AND, OR, XOR, NOT, Left Shift, Right Shift
With examples and demonstrations
"""


def demonstrate_and(a, b):
    return a & b


def demonstrate_or(a, b):
    return a | b


def demonstrate_xor(a, b):
    return a ^ b


def demonstrate_not(a):
    return ~a


def demonstrate_left_shift(a, n):
    return a << n


def demonstrate_right_shift(a, n):
    return a >> n


